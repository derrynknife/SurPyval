def multistate(seed):
    """An illness-death model with recovery and constant hazards
    (healthy -> ill 0.3, healthy -> dead 0.1, ill -> healthy 0.4, ill ->
    dead 0.3) for 300 units, each first seen at a uniform time in (0, 1)
    (delayed entry: a unit dead by then is never seen; a unit can enter
    ill) and censored at a uniform time in (2, 8). Times are rounded to
    two decimals, which ties some of them; a spell that rounding would
    leave empty is given 0.01."""
    rng = np.random.default_rng(seed)
    # (from, to, rate); states 1 healthy, 2 ill, 3 dead
    moves = [(1, 2, 0.3), (1, 3, 0.1), (2, 1, 0.4), (2, 3, 0.3)]
    rows = []
    for unit in range(1, 301):
        entry = round(float(rng.uniform(0, 1)), 2)
        cens = round(float(rng.uniform(2, 8)), 2)
        t, state, spells = 0.0, 1, []
        while True:
            out = [m for m in moves if m[0] == state]
            total = sum(m[2] for m in out)
            nt = t + rng.exponential(1 / total)
            if nt >= cens:
                spells.append([t, cens, state, None])
                break
            k = rng.choice(len(out), p=[m[2] / total for m in out])
            spells.append([t, nt, state, out[k][1]])
            t, state = nt, out[k][1]
            if state == 3:
                break
        spells = [sp for sp in spells if sp[1] > entry]
        if not spells:
            continue
        spells[0][0] = max(spells[0][0], entry)
        for k, sp in enumerate(spells):
            sp[0] = spells[k - 1][1] if k else round(sp[0], 2)
            sp[1] = round(sp[1], 2)
            if sp[1] <= sp[0]:
                sp[1] = round(sp[0] + 0.01, 2)
            rows.append((unit, sp[0], sp[1], sp[2], sp[3]))
    columns = list(zip(*rows))
    return {
        "source": "seeded synthetic, make_fixtures.multistate (rng {}): "
        "spells of an illness-death model with recovery, delayed entry "
        "and ties (state and e: 1 healthy, 2 ill, 3 dead; e null where the "
        "spell is censored)".format(seed),
        "columns": {
            "id": _native(columns[0]),
            "tl": _native(columns[1]),
            "x": _native(columns[2]),
            "state": _native(columns[3]),
            "e": list(columns[4]),
        },
    }


def clustered(seed):
    """Clustered event times for the mixed-effects Cox model: 12
    hospitals of 3 wards each (wards nested in hospitals) and 6 batches
    crossed with them, 432 rows. The log-hazard has a random intercept
    per hospital (sd 0.5), per ward (sd 0.3) and per batch (sd 0.3), and a
    random slope of ``trt`` per hospital (sd 0.4, correlation 0.5 with the
    hospital's intercept), on top of ``0.5 trt + 0.3 age`` and a Weibull
    (shape 1.3) baseline. A quarter of the rows enter late (``tl``) and
    are kept only if they survive to it; ``sex`` is a stratum. Times are
    rounded to one decimal, which ties some of them."""
    rng = np.random.default_rng(seed)
    n_hosp, n_ward, n_batch, per_ward = 12, 3, 6, 12
    sd = np.array([0.5, 0.4])
    corr = np.array([[1.0, 0.5], [0.5, 1.0]])
    hosp_re = rng.multivariate_normal(
        np.zeros(2), corr * np.outer(sd, sd), n_hosp
    )
    ward_re = rng.normal(0, 0.3, (n_hosp, n_ward))
    batch_re = rng.normal(0, 0.3, n_batch)
    rows = []
    for h in range(n_hosp):
        for w in range(n_ward):
            for _ in range(per_ward):
                trt = int(rng.binomial(1, 0.5))
                age = round(float(rng.normal(0, 1)), 1)
                sex = int(rng.binomial(1, 0.5)) + 1
                batch = int(rng.integers(n_batch)) + 1
                lp = (
                    0.5 * trt
                    + 0.3 * age
                    + hosp_re[h, 0]
                    + hosp_re[h, 1] * trt
                    + ward_re[h, w]
                    + batch_re[batch - 1]
                )
                late = rng.uniform() < 0.25
                tl = round(float(rng.uniform(0, 2)), 1) if late else 0.0
                while True:
                    t = 8 * rng.weibull(1.3) * np.exp(-lp / 1.3)
                    if t > tl + 0.1:
                        break
                cens = tl + rng.uniform(2, 15)
                x = round(float(min(t, cens)), 1)
                c = int(cens < t)
                rows.append((x, c, tl, trt, age, sex, h + 1, w + 1, batch))
    cols = list(zip(*rows))
    names = ["x", "c", "tl", "trt", "age", "sex", "hospital", "ward"]
    columns = {k: _native(v) for k, v in zip(names + ["batch"], cols)}
    return {
        "source": "seeded synthetic, make_fixtures.clustered (rng {}): "
        "c 1 is censored; ward is numbered within its hospital".format(seed),
        "columns": columns,
    }


