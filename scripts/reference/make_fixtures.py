def _native(values):
    """A list of plain floats/ints with ``None`` for NaN or infinity, so
    the file is strict JSON."""
    out = []
    for v in np.asarray(values).tolist():
        if isinstance(v, float) and not math.isfinite(v):
            out.append(None)
        else:
            out.append(v)
    return out


